"""Reproducible initial commit. The same tree always gives the same commit id: identity and date are fixed,
and the caller's git configuration, templates and hooks are never read (they could sign, rewrite line endings
or run code)."""

from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
from pathlib import Path

from lrc import __version__
from lrc.errors import ErrorCode, LrcError

BRANCH = "main"
IDENTITY = ("LRC", "lrc@outer-void.invalid")
DATE = "1980-01-01T00:00:00+0000"  # the ZIP epoch: fixed, and accepted by every git version
TIMEOUT_S = 120


def executable() -> str:
    exe = shutil.which("git")
    if exe is None:
        raise LrcError(ErrorCode.GIT_UNAVAILABLE, "The spec asks for an initial commit, but git is not on PATH.")
    return exe


def _env(home: Path) -> dict[str, str]:
    env = {k: os.environ[k] for k in ("PATH", "SYSTEMROOT", "TMPDIR", "TEMP", "TMP") if k in os.environ}
    name, email = IDENTITY
    env.update(
        {
            "HOME": str(home),
            "GIT_CONFIG_NOSYSTEM": "1",
            "GIT_CONFIG_GLOBAL": os.devnull,
            "GIT_TERMINAL_PROMPT": "0",
            "LC_ALL": "C",
            "TZ": "UTC",
            "GIT_AUTHOR_NAME": name,
            "GIT_AUTHOR_EMAIL": email,
            "GIT_AUTHOR_DATE": DATE,
            "GIT_COMMITTER_NAME": name,
            "GIT_COMMITTER_EMAIL": email,
            "GIT_COMMITTER_DATE": DATE,
        }
    )
    return env


CONFIG = (
    "-c",
    "core.autocrlf=false",
    "-c",
    "core.fileMode=true",
    "-c",
    "core.symlinks=true",
    "-c",
    "commit.gpgsign=false",
    "-c",
    f"init.defaultBranch={BRANCH}",
)


def initial_commit(root: Path, plan_id: str) -> dict[str, str]:
    exe = executable()
    with tempfile.TemporaryDirectory(prefix="lrc-git-") as scratch:
        templates = Path(scratch) / "templates"
        templates.mkdir()
        env = _env(Path(scratch))
        message = f"Initial commit\n\nGenerated by LRC {__version__}.\nlrc-plan-id: {plan_id}\n"
        steps = (
            ["init", "-q", f"--template={templates}", "-b", BRANCH],
            ["add", "-A"],
            ["commit", "-q", "--no-verify", "--no-gpg-sign", "-m", message],
            ["rev-parse", "HEAD"],
        )
        out = ""
        for args in steps:
            try:
                proc = subprocess.run(
                    [exe, *CONFIG, *args], cwd=root, env=env, capture_output=True, timeout=TIMEOUT_S, check=False
                )
            except (OSError, subprocess.TimeoutExpired) as exc:
                raise LrcError(ErrorCode.GIT_FAILED, f"git {args[0]} could not run: {type(exc).__name__}.") from None
            if proc.returncode != 0:
                tail = proc.stderr.decode("utf-8", "replace").strip().splitlines()[-1:] or [""]
                raise LrcError(
                    ErrorCode.GIT_FAILED,
                    f"git {args[0]} failed (exit {proc.returncode}).",
                    details={"step": args[0], "exit_code": proc.returncode, "stderr_tail": tail[0][:300]},
                )
            out = proc.stdout.decode("ascii", "replace").strip()
    return {"commit": out, "branch": BRANCH}
